/* Minimal Code 128 (subset B) barcode -> SVG. Works with any USB barcode scanner. */
(function () {
  const P = ['212222', '222122', '222221', '121223', '121322', '131222', '122213', '122312', '132212', '221213', '221312', '231212', '112232',
    '122132', '122231', '113222', '123122', '123221', '223211', '221132', '221231', '213212', '223112', '312131', '311222', '321122',
    '321221', '312212', '322112', '322211', '212123', '212321', '232121', '111323', '131123', '131321', '112313', '132113', '132311',
    '211313', '231113', '231311', '112133', '112331', '132131', '113123', '113321', '133121', '313121', '211331', '231131', '213113',
    '213311', '213131', '311123', '311321', '331121', '312113', '312311', '332111', '314111', '221411', '431111', '111224', '111422',
    '121124', '121421', '141122', '141221', '112214', '112412', '122114', '122411', '142112', '142211', '241211', '221114', '413111',
    '241112', '134111', '111242', '121142', '121241', '114212', '124112', '124211', '411212', '421112', '421211', '212141', '214121',
    '412121', '111143', '111341', '131141', '114113', '114311', '411113', '411311', '113141', '114131', '311141', '411131', '211412',
    '211214', '211232', '2331112'];

  function encode(text) {
    const codes = [104];
    for (const ch of String(text)) {
      const c = ch.charCodeAt(0) - 32;
      codes.push(c >= 0 && c < 95 ? c : 0);
    }
    let sum = 104;
    for (let i = 1; i < codes.length; i++) sum += codes[i] * i;
    codes.push(sum % 103);
    codes.push(106);
    return codes.map((c) => P[c]).join('');
  }

  window.Barcode = {
    svg(text, opts) {
      opts = opts || {};
      const h = opts.height || 40;
      const pattern = encode(text);
      const quiet = 10;
      let x = quiet;
      let bars = '';
      for (let i = 0; i < pattern.length; i++) {
        const w = Number(pattern[i]);
        if (i % 2 === 0) bars += `<rect x="${x}" y="0" width="${w}" height="${h}"/>`;
        x += w;
      }
      const total = x + quiet;
      return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${total} ${h}" preserveAspectRatio="none" style="width:${opts.width || '100%'};height:${opts.cssHeight || h + 'px'};display:block">` +
        `<g fill="#000">${bars}</g></svg>`;
    }
  };
})();
